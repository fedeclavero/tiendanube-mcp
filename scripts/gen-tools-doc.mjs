// Generates guides/TOOLS.md from the tool definitions. Run: npm run docs
import { writeFileSync } from "node:fs";
import { MODULES, countTools } from "../dist/server.js";
import { CUSTOM_TOOLS } from "../dist/tools/custom_meta.js";

const LABELS = {
  store: "Store & media",
  catalog: "Catalog, inventory & price lists",
  orders_sales: "Orders, fulfillment & carts",
  customers: "Customers",
  marketing: "Coupons & promotions",
  logistics: "Locations, shipping & business rules",
  payments_billing: "Payments, disputes, invoices & app billing",
  content_customization: "Pages, blog, email templates & scripts",
  extensibility_webhooks: "Metafields, custom fields, custom objects & webhooks",
};

let out = `# Tool reference

<!-- Generated by scripts/gen-tools-doc.mjs — do not edit by hand. -->

${countTools()} tools: ${MODULES.flatMap((m) => m.tools).length} API tools + ${CUSTOM_TOOLS.length} helper tools (guide and workflows) + \`tiendanube_oauth_exchange_code\`. In read-only mode (\`configure --read-only\` or \`TIENDANUBE_READ_ONLY=true\`) ${countTools(true)} tools are registered: the ${MODULES.flatMap((m) => m.tools).filter((t) => t.method === "GET").length} API read tools and the ${CUSTOM_TOOLS.filter((t) => !t.writeOnly).length} read-safe helpers.

Naming: \`tiendanube_<domain>_<action>\`. Every tool lists its HTTP route and required OAuth scope in its description, and carries MCP annotations (\`readOnlyHint\`, \`destructiveHint\`, \`idempotentHint\`).

| Domain | Tools |
| --- | ---: |
${MODULES.map((m) => `| ${LABELS[m.name] ?? m.name} | ${m.tools.length} |`).join("\n")}
| Guide & workflows | ${CUSTOM_TOOLS.length} |
`;
for (const m of MODULES) {
  out += `\n## ${LABELS[m.name] ?? m.name}\n\n| Tool | Route | Scope | Effect |\n| --- | --- | --- | --- |\n`;
  for (const t of m.tools) {
    const effect = t.method === "GET" ? "read" : t.method === "DELETE" || t.annotations?.destructiveHint ? "**destructive**" : "write";
    out += `| \`${t.name}\` | \`${t.method} ${t.path}\`${t.version === "unstable" ? " *(unstable)*" : ""} | ${t.scope} | ${effect} |\n`;
  }
}
out += `\n## Guide & workflows\n\nStart with \`tiendanube_start_here\`.\n\n| Tool | What it does | Read-only mode |\n| --- | --- | :---: |\n${CUSTOM_TOOLS.map((t) => `| \`${t.name}\` | ${t.summary} | ${t.writeOnly ? "no" : "yes"} |`).join("\n")}\n`;
writeFileSync(new URL("../guides/TOOLS.md", import.meta.url), out);
const counts = Object.fromEntries(MODULES.map((m) => [m.name, m.tools.length]));
console.log(JSON.stringify({ total: countTools(), counts }));
